#!/usr/bin/env python3
"""Derive the student view of an exercise from its solution sources.

The solution sources are the single source of truth: develop them normally, and this
script produces the version the students work in by eliding the regions they are meant
to write themselves. Regions are marked with line directives, which are ordinary
comments and therefore do not disturb the solution build:

    //## gap: histogram binning
    //  Walk the image with withPixels() and count how often each code value occurs.
    //## solution
    <the code the students must write themselves>
    //## end

    //## stub: the sRGB transfer function
    <the code the students must write themselves>
    //## end

Inside a region, whatever students should see goes into a "gap" section and everything
that gets elided goes into a "solution" section; the two may appear in either order and
may alternate. "stub" is shorthand for a region that must stay syntactically complete (a
function or loop body): it keeps any "gap" prompt and adds a throwing stub, so the
student view both compiles and reports at runtime which part is still missing. A stub
needs <stdexcept>, and belongs in a statement position.

Only files containing directives are written into the destination; all other files are
shared between the two views and stay where they are. Directive lines never reach the
student view. Invoke the script from the repository root, so that the source paths it
records in the generated banner stay stable.

usage:
    tools/elide.py 0intro/src 0intro/handout            # write the student view
    tools/elide.py 0intro/src 0intro/handout --check    # verify it is current (CI)
"""

import argparse
import re
import sys
from pathlib import Path

BANNER = """// STARTING POINT - implement the sections marked TODO in this file.
// Generated by tools/elide.py from {source}, which holds the reference solution; re-running
// the generator after changing that solution overwrites this whole file.
"""

KEYWORDS = ("gap", "solution", "stub")


class Region:
    """One marked region, collecting the lines of each of its sections."""

    def __init__ (self, keyword, title, indent):
        self.keyword = keyword
        self.title = title
        self.indent = indent
        self.prompt = []
        self.solution = []
        self.section = self.prompt if keyword == "gap" else self.solution

    def render (self):
        """Contribute this region's lines to the student view."""
        prompt = _trim(self.prompt)
        if self.keyword != "stub":
            if not any(line.strip() for line in prompt):
                return []
            return _heading(self) + prompt

        message = self.title or "not implemented yet"
        return _heading(self) + prompt + [f'{self.indent}throw std::logic_error("TODO: {message}");\n']


def _heading (region):
    """A normalized prompt heading, so the directive's title is not lost."""
    return [f"{region.indent}// TODO: {region.title}\n"] if region.title else []


def _trim (lines):
    """Drop blank lines at both ends, so elision does not leave ragged whitespace."""
    start, end = 0, len(lines)
    while start < end and not lines[start].strip():
        start += 1
    while end > start and not lines[end - 1].strip():
        end -= 1
    return lines[start:end]


def directive (comment):
    """Recognize a directive line; tolerates indentation and trailing whitespace."""
    prefix = rf"^(?P<indent>[ \t]*){re.escape(comment)}\s*##\s*"
    return re.compile(rf"{prefix}(?:(?P<keyword>{'|'.join(KEYWORDS)})\b"
                      rf"(?:\s*:\s*(?P<title>.*?))?|(?P<end>end)\b)\s*$")


def elide (lines, pattern):
    """Return the student-visible lines and the regions that were elided."""
    visible, regions, region = [], [], None
    for number, line in enumerate(lines, 1):
        match = pattern.match(line.rstrip("\n"))
        if match and match.group("keyword") is not None:
            keyword = match.group("keyword")
            if region and keyword in ("gap", "solution"):
                # A region may switch between its prompt and its solution, e.g. to put a hint first.
                region.section = region.prompt if keyword == "gap" else region.solution
            elif region:
                raise ValueError(f"line {number}: '{keyword}' inside an open '{region.keyword}' region")
            else:
                region = Region(keyword, (match.group("title") or "").strip(), match.group("indent"))
        elif match:
            if not region:
                raise ValueError(f"line {number}: 'end' without an open region")
            regions.append(region)
            visible.extend(region.render())
            region = None
        elif region:
            region.section.append(line)
        else:
            visible.append(line)
    if region:
        raise ValueError(f"unterminated '{region.keyword}' region")

    # A blank first line keeps the banner clear of the file's own content.
    if visible and visible[0].strip():
        visible.insert(0, "\n")
    return visible, regions


def build (src, comment):
    """Produce {relative path: student text} for every source that has directives."""
    pattern = directive(comment)
    files, report = {}, []
    for source in sorted(path for path in src.rglob("*") if path.is_file()):
        lines = source.read_text().splitlines(keepends=True)
        if not any(pattern.match(line.rstrip("\n")) for line in lines):
            continue
        relative = source.relative_to(src)
        try:
            visible, regions = elide(lines, pattern)
        except ValueError as error:
            raise SystemExit(f"{src}/{relative}: {error}") from error
        files[relative] = BANNER.format(source=f"{src}/{relative}") + "".join(visible)
        for region in regions:
            report.append(f"  {relative}: {region.keyword}"
                          f"{f' ({region.title})' if region.title else ''}"
                          f", {len(region.solution)} line(s) elided")
    return files, report


def main ():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("src", type=Path, help="solution sources (the source of truth)")
    parser.add_argument("dest", type=Path, help="student view (generated)")
    parser.add_argument("--comment", default="//", help="directive comment prefix")
    parser.add_argument("--check", action="store_true",
                        help="only verify that the student view is current")
    parser.add_argument("--quiet", action="store_true", help="report problems only")
    args = parser.parse_args()

    if not args.src.is_dir():
        raise SystemExit(f"{args.src}: not a directory")

    files, report = build(args.src, args.comment)

    if args.check:
        problems = [f"{args.dest / relative} is stale"
                    for relative, text in files.items()
                    if not (args.dest / relative).is_file()
                    or (args.dest / relative).read_text() != text]
        problems += [f"{path} has no directives left"
                     for path in sorted(args.dest.rglob("*"))
                     if path.is_file() and path.relative_to(args.dest) not in files]
        if problems:
            print("\n".join(problems), file=sys.stderr)
            print(f"\nrun: tools/elide.py {args.src} {args.dest}", file=sys.stderr)
            return 1
        if not args.quiet:
            print(f"{args.dest}: {len(files)} generated file(s) up to date")
        return 0

    if args.dest.is_dir():
        for path in sorted(args.dest.rglob("*")):
            if path.is_file() and path.relative_to(args.dest) not in files:
                print(f"removing {path}, which has no directives left", file=sys.stderr)
                path.unlink()
    for relative, text in files.items():
        target = args.dest / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    if not args.quiet:
        print("\n".join(report))
        print(f"wrote {len(files)} file(s) to {args.dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
